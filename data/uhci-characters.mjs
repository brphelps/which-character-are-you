const BASELINE_SOURCE = "henson-personality-index-baselines.md";

function character({
  id,
  name,
  universe,
  sourceOrder,
  scores,
  image = null,
  description = null,
  context = null,
  variantOf = null,
  exactDuplicateGroup = null,
}) {
  return Object.freeze({
    id,
    name,
    universe,
    context,
    variantOf,
    exactDuplicateGroup,
    scores: Object.freeze(scores),
    image,
    description,
    source: Object.freeze({
      file: BASELINE_SOURCE,
      orderWithinUniverse: sourceOrder,
    }),
  });
}

